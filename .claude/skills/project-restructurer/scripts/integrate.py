#!/usr/bin/env python3
"""
integrate.py — Write the handoff files.

Reads RESTRUCTURE_STATE.json at <dest> and writes INTEGRATION.md, the
human-readable handoff. The STATE json is the machine source of truth; this
turns it into a document any agent or human can start from — and, crucially,
tells them WHERE to begin rather than making them read everything.

Usage:
  python3 integrate.py --dest <output-folder>
"""
import argparse
import json
import os

LAYER_DESC = {
    "Frontend": "UI the user sees — components, pages, styles (the dining area)",
    "Backend": "business logic, controllers, services, routes (the kitchen)",
    "Database": "schemas, migrations, models, seeds (the store room)",
    "Server": "entrypoint, hosting, containers, CI/CD (the whole building)",
    "Integrations": "third-party clients: payments, auth, email, maps (the waiter)",
    "_shared": "project-wide config and docs used across layers",
    # Buckets a plan may add when the five-layer model genuinely does not fit.
    "Devices": "self-contained per-device installer bundles (kept whole)",
    "archive": "cold storage: superseded or regenerable files, nothing live",
}

# Likely entrypoint filenames per layer, best-effort.
ENTRY_HINTS = {
    "Server": ["index.js", "main.py", "server.js", "app.py", "manage.py",
               "docker-compose.yml", "Dockerfile", "deploy.sh"],
    "Frontend": ["App.tsx", "App.jsx", "index.html", "main.tsx", "main.js"],
    "Backend": ["routes.js", "app.js", "api.py", "controller.js", "index.js"],
    "Database": ["schema.sql", "schema.prisma", "models.py"],
    "Integrations": [],
}

# Searched in every layer after its own hints miss. A layer with no recognised
# entrypoint still usually has a README explaining itself, and pointing at that
# beats printing nothing — the whole purpose of this section is to stop the next
# agent reading the tree at random.
GENERIC_HINTS = ["README.md", "readme.md"]

# A project whose routing lives in a deploy manifest has no single "open this
# first" file for its API — the manifest IS the index. Naming it is far more
# useful than reporting no entrypoint at all.
ROUTE_MANIFESTS = ["vercel.json", "netlify.toml", "serverless.yml",
                   "docker-compose.yml", "Procfile"]


def find_entry(dest, layer):
    ldir = os.path.join(dest, layer)
    if not os.path.isdir(ldir):
        return None
    present = set()
    for r, _, files in os.walk(ldir):
        for f in files:
            present.add(f)
    for cand in list(ENTRY_HINTS.get(layer, [])) + GENERIC_HINTS:
        if cand in present:
            # return the actual relative path
            for r, _, files in os.walk(ldir):
                if cand in files:
                    rel = os.path.relpath(os.path.join(r, cand), dest)
                    return rel.replace("\\", "/")  # handoff paths stay portable
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", required=True)
    args = ap.parse_args()
    dest = os.path.abspath(args.dest)

    with open(os.path.join(dest, "RESTRUCTURE_STATE.json"),
              encoding="utf-8") as fh:
        state = json.load(fh)

    # Take the layer list from the state file, not a hardcoded one. A plan may
    # legitimately add a bucket the five-layer model has no name for — e.g. a
    # `Devices/` folder of self-contained installer bundles — and a hardcoded
    # list silently omits it from the handoff, which is the one document the
    # next agent is told to trust.
    declared = state.get("layers") or ["Frontend", "Backend", "Database",
                                       "Server", "Integrations", "_shared"]
    layers_present = [l for l in declared
                      if os.path.isdir(os.path.join(dest, l))]

    moved = [m for m in state["moves"] if m.get("status") == "moved"]
    counts = {}
    for m in moved:
        counts[m["layer"]] = counts.get(m["layer"], 0) + 1

    # Phase 4 is this script, so once it writes the handoff the pipeline is
    # done. Advance the token before rendering anything, or the next agent
    # reads "phase4_integrate" and re-runs this phase forever.
    if state.get("resume_point") == "phase4_integrate":
        state["resume_point"] = "done"
        with open(os.path.join(dest, "RESTRUCTURE_STATE.json"), "w",
                  encoding="utf-8") as fh:
            json.dump(state, fh, indent=2)

    lines = []
    lines.append("# Integration & Handoff Guide\n")
    lines.append("> Generated by **project-restructurer**. This file is the "
                 "starting point for any human or agent picking up this "
                 "project. Read the STATE file (`RESTRUCTURE_STATE.json`) for "
                 "the machine-readable detail.\n")

    # Start Here
    lines.append("## Start Here\n")
    lines.append(
        f"This project has been reorganized into a standard five-layer "
        f"architecture ({', '.join(layers_present)}). {len(moved)} files were "
        f"moved into their correct layer. **Next action:** "
        f"`{state.get('resume_point', 'review the layout')}` — see *Resume "
        f"Point* below. If you are an agent continuing this work, begin at the "
        f"entry points listed under *Entry Points*, not by scanning every "
        f"file.\n")

    # Where things live
    lines.append("## Where things live\n")
    lines.append("| Layer | Path | Files | What it holds |")
    lines.append("|-------|------|-------|----------------|")
    for layer in layers_present:
        lines.append(f"| {layer} | `./{layer}/` | {counts.get(layer, 0)} | "
                     f"{LAYER_DESC.get(layer, '')} |")
    lines.append("")

    # Entry points
    lines.append("## Entry Points — where to begin\n")
    any_entry = False
    for layer in layers_present:
        entry = find_entry(dest, layer)
        if entry:
            any_entry = True
            lines.append(f"- **{layer}** → open `./{entry}` first.")
    manifest = next((m for m in ROUTE_MANIFESTS
                     if os.path.isfile(os.path.join(dest, m))), None)
    if manifest:
        lines.append(f"- **Routing / API surface** → `./{manifest}` maps every "
                     f"URL to the file that serves it. For this project that "
                     f"manifest is the index of the backend, not any one "
                     f"source file.")
        any_entry = True
    if not any_entry:
        lines.append("- No obvious entrypoint detected automatically. Open "
                     "`Server/` first to find how the app boots.")
    lines.append("")

    # How layers talk
    lines.append("## How the layers talk\n")
    lines.append(
        "```\n"
        "Frontend  --(API request)-->  Backend  --(query)-->  Database\n"
        "                                 |\n"
        "                                 └--(calls)--> Integrations "
        "(payments, auth, email, maps)\n"
        "\n"
        "All of the above runs inside → Server (hosting / the building)\n"
        "```\n")
    lines.append(
        "Analogy: Frontend is the dining area, Backend is the kitchen, "
        "Database is the store room, Integrations is the waiter carrying "
        "orders in and out, and Server is the whole building it all runs in.\n")

    # Resume point
    lines.append("## Resume Point\n")
    lines.append(f"- Machine field `resume_point` = "
                 f"`{state.get('resume_point')}`.")
    if state.get("resume_detail"):
        lines.append(f"- {state['resume_detail']}")
    if state.get("backup"):
        backup = state["backup"]
        # The recovery path is not always a directory. An in-place run driven by
        # `git mv` is recovered with a git command, not a folder — relpath() on
        # that sentence produces a mangled pseudo-path, which is worse than no
        # line at all in the one document the next agent is told to trust.
        if os.path.isdir(backup):
            lines.append(f"- Full backup of the original structure is at "
                         f"`{os.path.relpath(backup, dest)}/` — nothing is "
                         f"lost; removed folders are recoverable here.")
        else:
            lines.append(f"- How to recover the original structure: {backup}")
    if state.get("removed"):
        lines.append(f"- Old folders/scripts removed: "
                     f"{', '.join(state['removed'][:20])}"
                     f"{' ...' if len(state['removed']) > 20 else ''}.")
    lines.append("")

    # Edits that were not simple moves. A next agent diffing the branch needs to
    # know which changes were content edits rather than relocations.
    if state.get("edits_beyond_moves"):
        lines.append("## Edits beyond moving files\n")
        lines.append("These are content changes, not relocations:\n")
        for e in state["edits_beyond_moves"]:
            lines.append(f"- {e}")
        lines.append("")

    # Evidence, not assurance. "Nothing was lost" is worth nothing as a claim;
    # it is worth something as a number the reader can re-derive.
    if state.get("verification"):
        lines.append("## Verification\n")
        lines.append("| Check | Result |")
        lines.append("|-------|--------|")
        for k, v in state["verification"].items():
            lines.append(f"| {k.replace('_', ' ')} | {v} |")
        lines.append("")

    # Open questions
    lines.append("## Open Questions / TODO for the next agent\n")
    oq = state.get("open_questions", [])
    if not oq:
        lines.append("- None. Every file classified with high confidence.")
    else:
        lines.append("These files were placed with low confidence — confirm "
                     "or move them:\n")
        for q in oq[:40]:
            conf = q.get("confidence")
            conf_s = f" ({int(conf*100)}%)" if isinstance(conf, (int, float)) else ""
            lines.append(f"- `{q.get('file')}`{conf_s} — {q.get('reason')}")
    lines.append("")

    # utf-8 explicitly: the template uses box-drawing and arrow characters that
    # blow up on Windows' cp1252 default.
    out = os.path.join(dest, "INTEGRATION.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"Wrote {out}")
    print(f"Layers present: {layers_present}")
    print(f"Open questions: {len(oq)}")


if __name__ == "__main__":
    main()
