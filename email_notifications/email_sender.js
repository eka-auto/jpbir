/**
 * Simple Email Sender for jaytibirthday.in Analytics
 * Sends daily reports to ekaaiurgaa@gmail.com
 */

const config = require('./email_config');
const nodemailer = require('nodemailer');
const fs = require('fs');
const path = require('path');

class EmailSender {
    constructor() {
        this.transporter = null;
        this.initialized = false;
        this.logFile = path.join(__dirname, 'logs', 'email_sender.log');
        
        // Ensure log directory exists
        if (!fs.existsSync(path.join(__dirname, 'logs'))) {
            fs.mkdirSync(path.join(__dirname, 'logs'), { recursive: true });
        }
    }
    
    // Initialize email transporter
    async initialize() {
        try {
            this.transporter = nodemailer.createTransport({
                host: config.email.host,
                port: config.email.port,
                secure: config.email.secure,
                auth: {
                    user: config.email.auth.user,
                    pass: config.email.auth.pass
                }
            });
            
            // Verify connection
            await this.transporter.verify();
            this.initialized = true;
            this.log('Email transporter initialized successfully');
            return true;
        } catch (error) {
            this.log(`Failed to initialize email transporter: ${error.message}`, 'error');
            return false;
        }
    }
    
    // Send daily analytics report
    async sendDailyReport(analyticsData) {
        if (!this.initialized) {
            await this.initialize();
            if (!this.initialized) {
                return { success: false, error: 'Email system not initialized' };
            }
        }
        
        try {
            const reportContent = this.generateDailyReport(analyticsData);
            
            const mailOptions = {
                from: config.email.from,
                to: config.recipients.join(', '),
                subject: config.templates.dailyReport.subject,
                text: reportContent,
                html: this.generateHTMLReport(analyticsData)
            };
            
            const info = await this.transporter.sendMail(mailOptions);
            this.log(`Daily report sent successfully. Message ID: ${info.messageId}`);
            
            return {
                success: true,
                messageId: info.messageId,
                recipients: config.recipients
            };
            
        } catch (error) {
            this.log(`Failed to send daily report: ${error.message}`, 'error');
            return { success: false, error: error.message };
        }
    }
    
    // Send system alert
    async sendAlert(alertType, alertData) {
        if (!this.initialized) {
            await this.initialize();
        }
        
        try {
            const alertContent = this.generateAlert(alertType, alertData);
            
            const mailOptions = {
                from: config.email.from,
                to: config.recipients.join(', '),
                subject: `${config.templates.alert.subject} - ${alertType}`,
                text: alertContent
            };
            
            const info = await this.transporter.sendMail(mailOptions);
            this.log(`Alert sent: ${alertType}. Message ID: ${info.messageId}`);
            
            return { success: true, messageId: info.messageId };
            
        } catch (error) {
            this.log(`Failed to send alert: ${error.message}`, 'error');
            return { success: false, error: error.message };
        }
    }
    
    // Generate simple daily report
    generateDailyReport(data) {
        const date = new Date().toLocaleDateString('en-IN', {
            weekday: 'long',
            year: 'numeric',
            month: 'long',
            day: 'numeric',
            timeZone: 'Asia/Kolkata'
        });
        
        return `
📊 jaytibirthday.in - Daily Analytics Report
${'='.repeat(50)}

Date: ${date}
Website: ${config.content.websiteUrl}

📈 Visitor Summary:
- Total Visitors: ${data.totalVisitors || 0}
- New Visitors: ${data.newVisitors || 0}
- Returning Visitors: ${data.returningVisitors || 0}

📍 Top Locations:
${this.formatLocations(data.locations || [])}

📱 Device Breakdown:
- Desktop: ${data.devices?.desktop || 0} visitors
- Mobile: ${data.devices?.mobile || 0} visitors
- Tablet: ${data.devices?.tablet || 0} visitors

⏰ Peak Hours:
${this.formatPeakHours(data.peakHours || [])}

🔗 Top Pages:
${this.formatTopPages(data.topPages || [])}

💡 Summary:
${data.summary || 'Normal traffic patterns observed.'}

🔒 Privacy Note:
All data is anonymized. No personal information is stored.

📊 Next Report: Tomorrow at 6:00 PM IST

${'='.repeat(50)}
Generated by jaytibirthday.in Analytics System
`;
    }
    
    // Generate HTML report (optional)
    generateHTMLReport(data) {
        return `
<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8">
    <title>${config.templates.dailyReport.subject}</title>
    <style>
        body { font-family: Arial, sans-serif; line-height: 1.6; color: #333; }
        .container { max-width: 600px; margin: 0 auto; padding: 20px; }
        .header { background: #f4f4f4; padding: 20px; text-align: center; }
        .section { margin: 20px 0; padding: 15px; background: #f9f9f9; }
        .metric { display: inline-block; margin: 10px; padding: 10px; background: #e3f2fd; }
        .footer { margin-top: 30px; padding-top: 20px; border-top: 1px solid #ddd; font-size: 12px; color: #666; }
    </style>
</head>
<body>
    <div class="container">
        <div class="header">
            <h1>📊 jaytibirthday.in Analytics Report</h1>
            <p>Daily visitor insights for your website</p>
        </div>
        
        <div class="section">
            <h2>📈 Visitor Summary</h2>
            <div class="metric"><strong>Total:</strong> ${data.totalVisitors || 0}</div>
            <div class="metric"><strong>New:</strong> ${data.newVisitors || 0}</div>
            <div class="metric"><strong>Returning:</strong> ${data.returningVisitors || 0}</div>
        </div>
        
        <div class="section">
            <h2>📍 Visitor Locations</h2>
            <ul>
                ${(data.locations || []).map(loc => `<li>${loc.country}: ${loc.count} visitors</li>`).join('')}
            </ul>
        </div>
        
        <div class="section">
            <h2>📱 Devices Used</h2>
            <p>Desktop: ${data.devices?.desktop || 0} | Mobile: ${data.devices?.mobile || 0} | Tablet: ${data.devices?.tablet || 0}</p>
        </div>
        
        <div class="footer">
            <p>This is an automated report from jaytibirthday.in analytics system.</p>
            <p>All data is anonymized for privacy protection.</p>
            <p>Report generated: ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}</p>
        </div>
    </div>
</body>
</html>
        `;
    }
    
    // Generate alert message
    generateAlert(alertType, alertData) {
        const timestamp = new Date().toLocaleString('en-IN', {
            timeZone: 'Asia/Kolkata',
            hour12: true
        });
        
        return `
⚠️ jaytibirthday.in - SYSTEM ALERT
${'='.repeat(50)}

Alert Type: ${alertType.toUpperCase()}
Time: ${timestamp}

Details:
${alertData.message || 'No additional details'}

${alertData.data ? `Data: ${JSON.stringify(alertData.data, null, 2)}` : ''}

Action Required: ${alertData.actionRequired || 'Monitor situation'}

${'='.repeat(50)}
jaytibirthday.in Analytics Monitoring
`;
    }
    
    // Helper methods
    formatLocations(locations) {
        if (!locations.length) return '  No location data available';
        return locations.slice(0, 5).map(loc => `  - ${loc.country}: ${loc.count} visitors`).join('\n');
    }
    
    formatPeakHours(hours) {
        if (!hours.length) return '  No peak hour data available';
        return hours.slice(0, 3).map(hour => `  - ${hour.hour}:00: ${hour.count} visitors`).join('\n');
    }
    
    formatTopPages(pages) {
        if (!pages.length) return '  No page data available';
        return pages.slice(0, 5).map(page => `  - ${page.url}: ${page.views} views`).join('\n');
    }
    
    // Logging
    log(message, level = 'info') {
        const timestamp = new Date().toISOString();
        const logEntry = `[${timestamp}] [${level.toUpperCase()}] ${message}\n`;
        
        // Write to log file
        fs.appendFileSync(this.logFile, logEntry, 'utf8');
        
        // Also log to console in development
        if (process.env.NODE_ENV !== 'production') {
            console.log(logEntry.trim());
        }
    }
    
    // Test email connection
    async testConnection() {
        try {
            const initialized = await this.initialize();
            if (!initialized) {
                return { success: false, error: 'Failed to initialize email transporter' };
            }
            
            // Send test email
            const testMailOptions = {
                from: config.email.from,
                to: config.recipients[0],
                subject: '✅ Test Email - jaytibirthday.in Analytics',
                text: 'This is a test email from your jaytibirthday.in analytics system.\n\nIf you receive this, email notifications are working correctly!'
            };
            
            const info = await this.transporter.sendMail(testMailOptions);
            this.log(`Test email sent successfully to ${config.recipients[0]}`);
            
            return {
                success: true,
                message: 'Test email sent successfully',
                messageId: info.messageId
            };
            
        } catch (error) {
            this.log(`Test email failed: ${error.message}`, 'error');
            return {
                success: false,
                error: error.message,
                hint: 'Make sure to set up Gmail app password in email_config.js'
            };
        }
    }
}

// Export singleton instance
const emailSender = new EmailSender();
module.exports = emailSender;